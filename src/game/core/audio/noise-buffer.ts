/** Brown-ish noise buffer (null when there is no audio context). */
export function noiseBuffer(ctx: AudioContext | null, sec = 2): AudioBuffer | null {
  if (!ctx) return null;
  const len = Math.floor(ctx.sampleRate * sec);
  const b = ctx.createBuffer(1, len, ctx.sampleRate);
  const d = b.getChannelData(0);
  let last = 0;
  for (let i = 0; i < len; i++) {
    const w = Math.random() * 2 - 1;
    last = (last + 0.02 * w) / 1.02;
    d[i] = last * 3.2;
  }
  return b;
}
